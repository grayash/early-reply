function hit(text, kw) {
  let i = text.indexOf(kw);
  if (i < 0) return false;
  const ex = EXCEPT.find((e) => e[0] === kw);
  if (!ex || !ex[1].length) return true;
  // 예외 낱말을 지운 뒤에도 남아 있으면 인정
  let t = text;
  for (const x of ex[1]) t = t.split(x).join(' ');
  return t.includes(kw);
}

/** 글에서 꼬리표와 분류 점수를 찾는다. */
export function classify(text) {
  const t = String(text || '').toLowerCase();
  const tags = {};
  for (const [tag, kws] of Object.entries(KW)) {
    let n = 0;
    for (const kw of kws) if (hit(t, kw)) n++;
    if (n) tags[tag] = Math.min(n, 2);
  }
  const cats = {};
  for (const [tag, n] of Object.entries(tags)) {
    const c = TAG_CAT[tag];
    cats[c] = (cats[c] || 0) + n;
  }
  const top = (list) => list.filter((c) => cats[c]).sort((a, b) => cats[b] - cats[a])[0] || null;
  let pol = 0;
  for (const [tag, n] of Object.entries(tags)) { if (POS_TAGS.has(tag)) pol += n; if (NEG_TAGS.has(tag)) pol -= n; }
  return { tags, cats, emotion: top(EMOTION_CATS), topic: top(TOPIC_CATS), found: Object.keys(tags).length, pol };
}
