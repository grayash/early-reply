CREATE TABLE IF NOT EXISTS posts (
  id TEXT PRIMARY KEY,
  text TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  day TEXT NOT NULL,
  quote_id TEXT NOT NULL,
  author_id TEXT NOT NULL,
  line TEXT,
  line_ai INTEGER NOT NULL DEFAULT 0,
  mood TEXT,
  how TEXT,
  owner_hash TEXT NOT NULL,
  likes INTEGER NOT NULL DEFAULT 0,
  dislikes INTEGER NOT NULL DEFAULT 0,
  reports INTEGER NOT NULL DEFAULT 0,
  hidden INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS posts_feed ON posts(hidden, created_at DESC);
CREATE INDEX IF NOT EXISTS posts_day ON posts(day, hidden);
CREATE TABLE IF NOT EXISTS votes (
  post_id TEXT NOT NULL, voter TEXT NOT NULL, v INTEGER NOT NULL,
  PRIMARY KEY (post_id, voter)
);
CREATE TABLE IF NOT EXISTS reports (
  post_id TEXT NOT NULL, voter TEXT NOT NULL,
  PRIMARY KEY (post_id, voter)
);
CREATE TABLE IF NOT EXISTS rate (
  k TEXT PRIMARY KEY, n INTEGER NOT NULL, exp INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS feedback (
  id INTEGER PRIMARY KEY AUTOINCREMENT, text TEXT NOT NULL, created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS emb (
  chunk INTEGER PRIMARY KEY, ver TEXT NOT NULL, n INTEGER NOT NULL, data BLOB NOT NULL
);
